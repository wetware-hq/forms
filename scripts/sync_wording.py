#!/usr/bin/env python3
"""Copy the signed wording into WORDING.md: line id + wording rows only (every fill-in value, such as
queue statuses and relationship words, is its own signed row), with the SHA-256 of that content in the header. Run locally when the signed file changes:

    python3 scripts/sync_wording.py SIGNED.md [--pending DRAFT.md ID[,ID...]]

--pending copies named, not-yet-signed lines from a draft into a separate section (reported by rulecheck).
The repo never reads the signed file itself; tests check WORDING.md against its own header hash."""
import hashlib, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROW = re.compile(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \| ([^|]*?) \|$", re.M)
HEAD = "# Signed wording (generated by scripts/sync_wording.py from the signed table; do not edit)"


def body(signed, pending=None):
    lines = ["| id | line |", "|---|---|"] + [f"| {k} | {v} |" for k, v in ROW.findall(signed)]
    if pending:
        lines += ["", "## Pending signature", "| id | line | status |", "|---|---|---|"]
        lines += [f"| {k} | {v} | pending |" for k, v in pending]
    return "\n".join(lines) + "\n"


def render(signed, pending=None):
    b = body(signed, pending)
    return f"{HEAD}\nsha256: {hashlib.sha256(b.encode()).hexdigest()}\n\n{b}"


def pending_rows(draft_path, ids):
    rows = dict(ROW.findall(pathlib.Path(draft_path).read_text()))
    return [(k, rows[k]) for k in ids]


def current_pending():
    t = (ROOT / "WORDING.md").read_text() if (ROOT / "WORDING.md").exists() else ""
    return re.findall(r"^\| ([A-Z]{2,4}-[A-Z0-9-]+) \| ([^|]*?) \| pending \|$", t, re.M)


def main(argv):
    """sync_wording.py SIGNED [--pending DRAFT ID,ID]. Without --pending, pending lines already in WORDING.md are kept
    unless they are signed now."""
    if len(argv) not in (2, 5) or (len(argv) == 5 and argv[2] != "--pending"):
        print(__doc__, file=sys.stderr)
        return 2
    signed = pathlib.Path(argv[1]).read_text()
    pend = pending_rows(argv[3], argv[4].split(",")) if len(argv) == 5 else current_pending()
    have = dict(ROW.findall(signed))
    pend = [(k, v) for k, v in pend if k not in have]
    (ROOT / "WORDING.md").write_text(render(signed, pend))
    print(f"WORDING.md: {len(have)} signed lines, {len(pend)} pending")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
